    def draw_cards(self, count: int = 1) -> List[TarotCard]:
        """Вытянуть карты"""
        cards = random.sample(self._get_card_set(), count)
        # Определяем перевёрнутость
        result = []
        for card in cards:
            is_reversed = random.random() < 0.35  # 35% шанс перевёрнутой
            # Создаём копию с флагом перевёрнутости (упрощённо через атрибут)
            result.append((card, is_reversed))
        return result
    
