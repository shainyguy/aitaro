    async def generate_reading(
        self,
        user_name: str,
        zodiac_sign: str,
        cards: List[tuple],  # List of (TarotCard, is_reversed)
        positions: List[str],
        question: str = None,
        reading_type: str = "general"
    ) -> str:
        """Генерация персонализированного расклада"""
        
        profile = self.get_zodiac_profile(zodiac_sign)
        moon_day = self._get_moon_day()
        
        # Собираем контекст
        context = self._build_context(user_name, profile, moon_day)
        
        # Анализируем карты
        cards_analysis = self._analyze_cards(cards, positions, question, reading_type)
        
        # Генерируем интерпретацию
        if gigachat_service:
            return await self._generate_ai_reading(context, cards_analysis, question)
        else:
            return self._generate_fallback_reading(context, cards_analysis, question)
    
    def _build_context(self, user_name: str, profile: dict, moon_day: int) -> dict:
        """Построение контекста"""
        return {
            "user_name": user_name,
            "element": profile["element"],
            "ruler": profile["ruler"],
            "strengths": profile["strengths"],
            "weaknesses": profile["weaknesses"],
            "advice_style": profile["advice_style"],
            "shadow": profile["shadow"],
            "moon_day": moon_day,
            "moon_energy": self._get_moon_energy(moon_day)
        }
    
    def _analyze_cards(
        self, 
        cards: List[tuple], 
        positions: List[str],
        question: str,
        reading_type: str
    ) -> List[dict]:
        """Анализ карт в контексте"""
        analysis = []
        
        for i, (card, is_reversed) in enumerate(cards):
            position = positions[i] if i < len(positions) else f"Карта {i+1}"
            
            # Выбираем интерпретацию по сфере
            if question and any(w in question.lower() for w in ["любов", "отношен", "партнёр"]):
                meaning = card.love_rev if is_reversed else card.love_up
            elif question and any(w in question.lower() for w in ["работ", "карьер", "проект"]):
                meaning = card.career_rev if is_reversed else card.career_up
            elif question and any(w in question.lower() for w in ["деньг", "финанс", "зарплат"]):
                meaning = card.money_rev if is_reversed else card.money_up
            else:
                meaning = card.advice_rev if is_reversed else card.advice_up
            
            analysis.append({
                "position": position,
                "card_name": card.name,
                "is_reversed": is_reversed,
                "keywords": card.reversed_keys if is_reversed else card.upright_keys,
                "meaning": meaning,
                "advice": card.advice_rev if is_reversed else card.advice_up,
                "timing": card.timing,
                "yes_no": "нет" if (card.yes_no == "yes" and is_reversed) or (card.yes_no == "no" and not is_reversed) else ("да" if card.yes_no == "yes" else "возможно")
            })
        
        return analysis
    
    def _get_moon_day(self) -> int:
        """Получить лунный день (упрощённо)"""
        from datetime import datetime
        day = datetime.now().day
        return (day % 30) + 1
    
    def _get_moon_energy(self, moon_day: int) -> str:
        """Энергия лунного дня"""
        if moon_day in [1, 2, 3]:
            return "растущая, время новых начинаний"
        elif moon_day in [14, 15, 16]:
            return "полнолуние, эмоции на пике"
        elif moon_day in [28, 29, 30]:
            return "убывающая, время завершений и отпускания"
        else:
            return "стабильная"
    
